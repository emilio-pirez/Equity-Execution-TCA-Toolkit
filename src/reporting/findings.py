"""Generate results/findings.md: every headline number computed from results tables.

The README quotes these numbers; re-running the pipeline regenerates them, so every
figure is traceable to a CSV in results/ and a formula in src/.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from src.reporting.charts import SHORT


def _md(df: pd.DataFrame, floatfmt: str = "{:.1f}") -> str:
    """Minimal markdown table (no tabulate dependency)."""
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, (float, np.floating)) else str(v) for v in r]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def build(liq, costs, prof, dq, syn, frontier, ac_sim, sens, bbg_val, ac_ticker) -> str:
    out = ["# Findings (auto-generated by `python -m src.pipeline`)", ""]
    first, last = dq["date"].min(), dq["date"].max()
    out += [f"Sample: {first} to {last}, {dq.groupby('ticker')['date'].nunique().max()} sessions of 1-minute bars (yfinance). "
            "Costs in bps, positive = cost. Simulated buys and sells pooled.", ""]

    # ---- Q1
    out += ["## Q1. Cost of executing 1/5/10/20% of ADV, by algorithm", ""]
    v = costs[costs["algo"] == "VWAP"].pivot(index="ticker", columns="pct_adv", values="is_total_bps")
    v.columns = [f"{c * 100:.0f}% ADV" for c in v.columns]
    v.index = [SHORT[t] for t in v.index]
    out += ["Mean implementation shortfall of a full-session **VWAP** order:", "", _md(v.reset_index(names="ticker")), ""]
    best = costs.loc[costs[costs["fill_rate"] > 0.99].groupby(["ticker", "pct_adv"])["is_total_bps"].idxmin()]
    safest = costs.loc[costs[costs["fill_rate"] > 0.99].groupby(["ticker", "pct_adv"])["is_std_bps"].idxmin()]
    tbl = best[["ticker", "pct_adv", "algo", "is_total_bps"]].merge(
        safest[["ticker", "pct_adv", "algo", "is_std_bps"]], on=["ticker", "pct_adv"], suffixes=("_cheapest", "_lowest_risk"))
    tbl["ticker"] = tbl["ticker"].map(SHORT)
    tbl["pct_adv"] = (tbl["pct_adv"] * 100).round().astype(int).astype(str) + "%"
    out += ["Cheapest and lowest-risk algorithm among those that complete (fill > 99%):", "", _md(tbl), ""]
    pov = costs[costs["algo"].str.startswith("POV")]
    low_fill = pov[pov["fill_rate"] < 0.99]
    out += [f"POV orders that could not complete within the session: {len(low_fill)} of {len(pov)} ticker-size cells "
            f"(e.g. POV10 at 20% ADV fills {low_fill['fill_rate'].min() * 100:.0f}-{low_fill['fill_rate'].max() * 100:.0f}%); "
            "their remainder is charged drift-to-close plus the next-day pre-trade cost.", ""]

    # ---- Q2
    out += ["## Q2. Mexico vs US", ""]
    m = liq.groupby("market").agg(spread_bps=("model_spread_bps", "median"), usd_per_bp=("usd_per_bp_1m", "median"),
                                  adv_usd_m=("adv_usd_m", "median"), exec_cov=("coverage_exec_vs_daily", "median"),
                                  daily_vol_bps=("daily_vol_bps", "median"))
    v5 = costs[(costs["algo"] == "VWAP") & np.isclose(costs["pct_adv"], 0.05)].merge(liq[["ticker", "market"]], on="ticker")
    m["vwap_5pct_bps"] = v5.groupby("market")["is_total_bps"].median()
    depth_ratio = m.loc["US", "usd_per_bp"] / m.loc["MX", "usd_per_bp"]
    out += [_md(m.reset_index(), "{:,.2f}"), "",
            f"- Median depth proxy: US names absorb **{depth_ratio:,.0f}x** more USD per bp of 1-minute price move than MX names.",
            f"- Median spread estimate: MX {m.loc['MX', 'spread_bps']:.2f} bps vs US {m.loc['US', 'spread_bps']:.2f} bps "
            "(US estimates are upper bounds: at 1-min frequency Corwin-Schultz is inflated by intra-minute volatility; "
            "a 1-cent quote on AAPL is ~0.3 bps).",
            f"- Only {m.loc['MX', 'exec_cov'] * 100:.0f}% of MX official daily volume is visible as executable continuous-session "
            f"volume in yfinance bars (US: {m.loc['US', 'exec_cov'] * 100:.0f}%): the rest is auctions, block crosses and, "
            "for BMV, the last trading hour that yfinance does not serve.",
            f"- Same %ADV costs about the same in the square-root model when volatility is similar - but 5% of ADV is "
            f"USD {m.loc['MX', 'adv_usd_m'] * 0.05:,.1f}m in the median MX name vs USD {m.loc['US', 'adv_usd_m'] * 0.05:,.0f}m in the US.", ""]

    # ---- Q3
    out += ["## Q3. Intraday liquidity", ""]
    for mk, g in prof.groupby("market"):
        p = g.groupby("bucket_min")[["volume_share", "spread_bps"]].mean()
        first_sp, mid_sp = p["spread_bps"].iloc[0], p["spread_bps"].iloc[len(p) // 2]
        top = p["volume_share"].idxmax()
        cheapest = p["spread_bps"].idxmin()
        out.append(f"- **{mk}**: first 30 min spread {first_sp:.2f} bps vs {mid_sp:.2f} bps mid-session "
                   f"({first_sp / mid_sp:.1f}x); largest volume bucket starts +{top / 60:.1f} h "
                   f"({p['volume_share'].max() * 100:.1f}% of volume); tightest spread at +{cheapest / 60:.1f} h.")
    out.append("")

    # ---- Q4
    out += [f"## Q4. Impact vs timing risk (Almgren-Chriss), {SHORT[ac_ticker]} 10% ADV", ""]
    s = ac_sim.copy()
    out += [_md(s[["label", "cost_bps", "risk_bps", "fill_rate"]]), ""]
    tw = s[s["label"] == "IS u=0"].iloc[0]
    u3 = s[s["label"] == "IS u=3"].iloc[0]
    out += [f"- Moving from TWAP (urgency 0) to IS urgency 3: cost {tw['cost_bps']:.1f} -> {u3['cost_bps']:.1f} bps "
            f"({u3['cost_bps'] - tw['cost_bps']:+.1f}), risk {tw['risk_bps']:.1f} -> {u3['risk_bps']:.1f} bps "
            f"({(u3['risk_bps'] / tw['risk_bps'] - 1) * 100:+.0f}%).",
            f"- Calibration: sigma per bar {frontier['sigma_bar_bps'].iloc[0]:.2f} bps, linear temp-impact eta "
            f"{frontier['eta_bps'].iloc[0]:.0f} bps, N = {frontier['n_bars'].iloc[0]} bars.", ""]

    # ---- Q5
    out += ["## Q5. Spread estimators vs truth", ""]
    r = syn.groupby(["estimator", "trades_per_minute"])["ratio"].mean().unstack(0)
    out += ["Synthetic bars with known spread (estimate / true, daily level, mean over spreads 2-20 bps and 5 seeds):", "",
            _md(r.reset_index(), "{:.2f}"), ""]
    if bbg_val is None or bbg_val.empty:
        out += ["Bloomberg validation: **pending** (no files in `data/raw/bbg/`).", ""]
    else:
        b = bbg_val[(bbg_val["level"] == "daily")][["ticker", "estimator", "ref_mean_bps", "est_mean_bps", "bias_bps", "corr"]]
        out += ["Bloomberg quoted spread vs estimators (daily level):", "", _md(b, "{:.2f}"), ""]

    # ---- sensitivity
    k = sens[np.isclose(sens["pct_adv"], 0.10)].pivot_table(index="ticker", columns="k", values="total_bps")
    k.index = [SHORT[t] for t in k.index]
    k.columns = [f"k={c}" for c in k.columns]
    out += ["## Impact-coefficient sensitivity (pre-trade model, 10% ADV)", "", _md(k.reset_index(names="ticker")), ""]
    return "\n".join(out)
